async function respondToComplaint(complaintId, inputId) {
  const responseText = document.getElementById(inputId)?.value?.trim();
  if (!responseText) return;

  try {
    const res = await fetch(`${API}/complaints/respond/${complaintId}/`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ teacher_email: teacherEmail, response: responseText })
    });
    const data = await res.json();
    if (data.status === 'success') {
      loadTeacherComplaints();
    }
  } catch (e) {}
}

